-- Keep purchases made before this migration charged to the adopted normal round.
-- Do not delete the legacy receipts, events, character saves, or other shop counts.
INSERT INTO diva_shop_legacy_anchor(singleton,event_id)
VALUES(true,(SELECT e.id FROM events e WHERE e.event_type='diva'
      AND NOT EXISTS(SELECT 1 FROM diva_debug_song_event d WHERE d.event_id=e.id)
      AND NOT EXISTS(SELECT 1 FROM diva_event_lifecycle l WHERE l.event_id=e.id AND l.mode IN (2,3))
    ORDER BY EXISTS(SELECT 1 FROM diva_event_lifecycle l WHERE l.event_id=e.id AND l.mode=-1) DESC,
             e.start_time DESC,e.id DESC LIMIT 1))
ON CONFLICT(singleton) DO NOTHING;
INSERT INTO diva_shop_purchases(event_id,char_id,shop_item_id,bought)
SELECT a.event_id,b.character_id,b.shop_item_id,b.bought
FROM shop_items_bought b JOIN shop_items s ON s.id=b.shop_item_id
JOIN characters ch ON ch.id=b.character_id CROSS JOIN diva_shop_legacy_anchor a
WHERE s.shop_type=8 AND s.shop_id=7 AND s.diva_round_limit AND a.event_id IS NOT NULL
ON CONFLICT(event_id,char_id,shop_item_id) DO NOTHING;
