-- GP exchange limits belong to the Diva round, not a calendar week or lifetime.
ALTER TABLE public.shop_items ADD COLUMN IF NOT EXISTS diva_round_limit boolean NOT NULL DEFAULT false;
CREATE TABLE IF NOT EXISTS public.diva_shop_purchases (
    event_id integer NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    char_id integer NOT NULL REFERENCES public.characters(id) ON DELETE CASCADE,
    shop_item_id integer NOT NULL REFERENCES public.shop_items(id) ON DELETE CASCADE,
    bought integer NOT NULL CHECK(bought >= 0),
    PRIMARY KEY(event_id,char_id,shop_item_id)
);
CREATE TABLE IF NOT EXISTS public.diva_shop_legacy_anchor (
    singleton boolean PRIMARY KEY CHECK(singleton),
    event_id integer REFERENCES public.events(id) ON DELETE SET NULL
);
