// These forms reuse a raw monster ID with another entry in the client log.
// Only artwork that is distinct in the supplied Namu Wiki table needs an
// override here; the remaining forms deliberately fall back to the base icon.
var dashboardMonsterVariantIcons = map[string]string{
	"violent_raviente": "namu_517a8fb942ea0258.webp",
}

func dashboardMonsterIcon(monsterID int, variantKind string) string {
	if icon := dashboardMonsterVariantIcons[variantKind]; icon != "" {
		return icon
	}
	if variantKind == "zenith" {
		if icon := dashboardMonsterZenithIcons[monsterID]; icon != "" {
			return icon
		}
	}
	switch variantKind {
	case "normal", "hardcore", "zenith", "senyu", "conquest", "shiten", "upper_shiten",
		"challenge", "hardcore_optional", "ul_fixed", "unknown",
		"phantom_red_rajang", "phantom_doragyurosu", "extreme_zinogre",
		"extreme_guanzorumu", "extreme_deviljho", "extreme_elzelion",
		"extreme_nargacuga", "extreme_duremudira", "extreme_bogabadorumu",
		"extreme_zerureusu":
		return dashboardMonsterNormalIcons[monsterID]
	default:
		return ""
	}
}
