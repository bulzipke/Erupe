	filters.WriteUint32(uint32(len(smc.Data())))
	filters.WriteBytes(smc.Data())

	nameParts, messageParts, selectedWords := selectNGWordParts(len(filters.Data()), words)

	filters.WriteNullTerminatedBytes([]byte("nam"))
	nam := byteframe.NewByteFrame()
	nam.SetLE()
	for _, rawParts := range nameParts {
		parts := normalizeClientNGWordParts(rawParts, smcData)
		nam.WriteUint32(uint32(len(parts)))
		for _, part := range parts {
			nam.WriteUint16(part.value)
			nam.WriteInt16(part.smcIndex)
		}
		nam.WriteUint16(0)
		nam.WriteInt16(-1)
	}
	nam.WriteUint32(0)
	filters.WriteUint32(uint32(len(nam.Data())))
	filters.WriteBytes(nam.Data())

	filters.WriteNullTerminatedBytes([]byte("msg"))
	msg := byteframe.NewByteFrame()
	msg.SetLE()
	for _, rawParts := range messageParts {
		parts := normalizeClientNGWordParts(rawParts, smcData)
		msg.WriteUint32(uint32(len(parts)))
		for _, part := range parts {
			msg.WriteUint16(part.value)
			msg.WriteInt16(part.smcIndex)
		}
		msg.WriteUint16(0)
		msg.WriteInt16(-1)
	}
	msg.WriteUint32(0)
	filters.WriteUint32(uint32(len(msg.Data())))
	filters.WriteBytes(msg.Data())

	return append([]byte(nil), filters.Data()...), selectedWords
