// KoreanName returns the localized name when one is registered, otherwise the
// canonical Monsters name. Add or correct dashboard names in KoreanNames.
func KoreanName(monsterID int) string {
	if name := KoreanNames[monsterID]; name != "" {
		return name
	}
	if monsterID >= 0 && monsterID < len(Monsters) {
		return Monsters[monsterID].Name
	}
	return ""
}
